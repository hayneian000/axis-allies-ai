export interface TerritoryDef {
  id: string;
  name: string;
  states: string;
  /** "land" or "sea". Sea zones are never owned, have 0 IPC, and hold naval units only. */
  domain: 'land' | 'sea';
  ipc: number;
  neighbors: string[];
  /** Stylized polygon approximating the real geography. */
  points: Array<[number, number]>;
  /** Additional disjoint polygons (e.g. Michigan's Upper Peninsula). */
  extraPolygons?: Array<Array<[number, number]>>;
  /** Label anchor for name/units text. */
  label: [number, number];
}

export interface MapData {
  name: string;
  viewBox: { width: number; height: number };
  territories: TerritoryDef[];
  /** Decorative water overlays (Great Lakes etc.); purely visual, never clickable.
   *  Polygons in viewBox coordinates, generated by scripts/build-map. */
  lakes?: Array<{ name: string; points: Array<[number, number]> }>;
}

