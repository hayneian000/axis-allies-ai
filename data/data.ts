export interface TerritoryDef {
  id: string;
  name: string;
  states: string;
  /** "land" or "sea". Sea zones are never owned, have 0 IPC, and hold naval units only. */
  domain: 'land' | 'sea';
  ipc: number;
  neighbors: string[];
  /** Stylized polygon approximating the real geography. */
  points: Array<[number, number]>;
  /** Additional disjoint polygons (e.g. Michigan's Upper Peninsula). */
  extraPolygons?: Array<Array<[number, number]>>;
  /** Label anchor for name/units text. */
  label: [number, number];
  /** Board-space name anchor (1942 map only): where the territory / sea-zone
   *  name text is drawn, from TripleA's name_place.txt. Distinct from
   *  `label` (the centers.txt anchor that unit icons sit on). */
  nameLabel?: [number, number];
  /** Board-space name nudge (1942 map only): a small [dx, dy] offset added
   *  to `nameLabel` when drawing the name, for territories whose authored
   *  name anchor collides with their starting unit stack. Emitted by the
   *  build script from its NAME_NUDGES table; absent = draw at the anchor. */
  nameNudge?: [number, number];
  /** Coarse world region (1942 map only; the America map groups by `states`). */
  region?: string;
  /** Starting power on the 1942 map: 'ussr' | 'germany' | 'uk' | 'japan' | 'us' | 'neutral'. Land only. */
  owner?: string;
  /** True for the 16 impassable neutral territories on the 1942 map. Land only. */
  neutral?: boolean;
  /** Capital city name if this territory holds a power's capital (1942 map). */
  capital?: string;
  /** Victory city name if this territory is a victory city (1942 map). */
  victoryCity?: string;
}

export interface MapData {
  name: string;
  viewBox: { width: number; height: number };
  territories: TerritoryDef[];
  /** Decorative water overlays (Great Lakes etc.); purely visual, never clickable.
   *  Polygons in viewBox coordinates, generated by scripts/build-map. */
  lakes?: Array<{ name: string; points: Array<[number, number]> }>;
  /** True when the map's coordinates are a board-raster space (TripleA
   *  3500x2000 for the 1942 map) rather than a geographic projection. */
  boardSpace?: boolean;
  /** Conditional canal passages (Panama, Suez). Each connects two sea zones
   *  but is only traversable when the moving power controls all `requires`
   *  territories. NOT included in TerritoryDef.neighbors; movement code must
   *  check canals separately. */
  canals?: Array<{
    id: string;
    zones: [string, string];
    requires: string[];
    description: string;
  }>;
  /** Territory pairs that are adjacent across the map's horizontal seam
   *  (left edge <-> right edge). Already included in `neighbors`; listed
   *  here so rendering can avoid drawing seam-crossing lines the long way. */
  wrapPairs?: Array<[string, string]>;
}

