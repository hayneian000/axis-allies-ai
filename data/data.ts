export interface ScenarioDef {
  players: number;
  /** One entry per seat: a single capital territory id, or — for a seat
   *  ruling more than one power (1942 seat 3: British + Americans) — an
   *  array of its capitals, primary first. */
  capitals: Array<string | string[]>;
  banks: number[];
  holdings: HoldingDef[];
  neutrals: Record<string, Partial<Record<UnitType, number>> | null>;
  /** Default garrison for neutral territories (null entries in `neutrals`). Defaults to 3 infantry. */
  neutralGarrison?: Partial<Record<UnitType, number>>;
  /** Capitals a player must hold simultaneously to win. Defaults to majority. */
  capitalsToWin?: number;
  /** Victory cities a seat must hold AT THE END OF A COMPLETE ROUND to
   *  win (1942 2e standard victory, rulebook p.6): either one threshold per
   *  seat (1942: each seat's starting victory-city count + 3, the per-seat
   *  form of the book's Axis 9 / Allies 10 side totals) or a single number
   *  applied to every seat. Absent = no victory-city win path. */
  victoryCitiesToWin?: number | number[];
  /** Display names for the seats, one per seat (1942: the power names -
   *  "Germany", "USSR", "Japan", "UK + US"). Used as the default player
   *  names when a game does not supply its own. */
  seatNames?: string[];
  /** Fixed turn order (seat ids, first to last). When present, createGame
   *  uses it verbatim instead of the seeded shuffle - the 1942 scenario
   *  plays in the 1942 2e power order (Germany, USSR, Japan, UK + US).
   *  Free-for-all scenarios without one keep the shuffled order. */
  turnOrder?: number[];
  /** Free-text provenance / conversion notes (e.g. the 1942 scenario's
   *  five-powers-to-four-seats merge and bank source). Display only. */
  note?: string;
}

