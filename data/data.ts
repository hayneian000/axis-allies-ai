/** The canal (if any) whose passage connects sea zones `a` and `b`. Canal
 *  edges ARE part of `neighbors`; traversing one additionally requires the
 *  moving power to control every territory in the canal's `requires` list
 *  (enforced by movement code, not by the adjacency data). */
export function canalBetween(
  a: string,
  b: string,
): { id: string; zones: [string, string]; requires: string[]; description: string } | undefined {
  return MAP.canals?.find(
    (c) => (c.zones[0] === a && c.zones[1] === b) || (c.zones[0] === b && c.zones[1] === a),
  );
}

/** BFS step-distance over all territories (aircraft ignore ground ownership).
 *  Impassable territories are neither destinations nor waypoints: aircraft
 *  may not fly over them (1942 2e), so routes bend around them and an
 *  impassable destination is unreachable (Infinity). */
export function airDistance(from: string, to: string): number {
  if (from === to) return 0;
  if (isImpassable(to)) return Infinity;
  const dist: Record<string, number> = { [from]: 0 };
  const queue = [from];
  while (queue.length > 0) {
    const cur = queue.shift()!;
    for (const n of neighborsOf(cur)) {
      if (isImpassable(n)) continue;
      if (dist[n] === undefined) {
        dist[n] = dist[cur] + 1;
        if (n === to) return dist[n];
        queue.push(n);
      }
    }
  }
  return Infinity;
}

/** Sea zones reachable within `maxSteps` sea moves, traveling only through
 *  zones where `passable` holds. Used for the 2-zone naval movement rule
 *  (1942 2e p.27: "All sea units can move up to two sea zones"). The
 *  optional `edgeOk` veto is consulted for every traversed edge (from, to)
 *  — canal enforcement hangs off it (see `canalBetween`). */
export function seaReachable(
  from: string,
  maxSteps: number,
  passable: (id: string) => boolean,
  edgeOk?: (from: string, to: string) => boolean,
): Set<string> {
  const seen = new Set<string>([from]);
  let frontier = [from];
  for (let step = 0; step < maxSteps; step++) {
    const next: string[] = [];
    for (const cur of frontier) {
      for (const n of neighborsOf(cur)) {
        if (!isSea(n) || seen.has(n) || !passable(n)) continue;
        if (edgeOk && !edgeOk(cur, n)) continue;
        seen.add(n);
        next.push(n);
      }
    }
    frontier = next;
  }
  seen.delete(from);
  return seen;
}

/**
 * Land paths of up to `maxSteps` from `from`, where each intermediate stop is
 * friendly-owned or blitzable (enemy-owned with zero units). Used for tanks.
 */
export function landPaths(
  from: string,
  maxSteps: number,
  isFriendly: (id: string) => boolean,
  isEmptyEnemy: (id: string) => boolean,
): string[][] {
  const paths: string[][] = [];
  const walk = (cur: string, stepsLeft: number, path: string[]) => {
    if (stepsLeft === 0) return;
    for (const n of neighborsOf(cur)) {
      if (path.includes(n)) continue;
      if (isImpassable(n)) continue; // impassable ground blocks land paths too
      if (!isFriendly(n) && !isEmptyEnemy(n)) continue;
      const next = [...path, n];
      paths.push(next);
      walk(n, stepsLeft - 1, next);
    }
  };
  walk(from, maxSteps, [from]);
  return paths;
}
