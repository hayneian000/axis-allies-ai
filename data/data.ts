export function scenarioFor(playerCount: number): ScenarioDef {
  const s = SCENARIOS[playerCount];
  if (!s) throw new Error(`No scenario for ${playerCount} players.`);
  return s;
}

const byId: Record<string, TerritoryDef> = Object.fromEntries(
  MAP.territories.map((t) => [t.id, t]),
);

export function territoryDef(id: string): TerritoryDef | undefined {
  return byId[id];
}

export function neighborsOf(id: string): string[] {
  return byId[id]?.neighbors ?? [];
}

export function areAdjacent(a: string, b: string): boolean {
  return neighborsOf(a).includes(b);
}

export function ipcOf(id: string): number {
  return byId[id]?.ipc ?? 0;
}

/** True for sea zones (never owned, 0 IPC, naval units only). */
export function isSea(id: string): boolean {
  return byId[id]?.domain === 'sea';
}

/** True for land territories (everything that is not a sea zone). */
export function isLand(id: string): boolean {
  return !!byId[id] && byId[id].domain !== 'sea';
}

export function landTerritoryIds(): string[] {
  return MAP.territories.filter((t) => t.domain !== 'sea').map((t) => t.id);
}

export function seaZoneIds(): string[] {
  return MAP.territories.filter((t) => t.domain === 'sea').map((t) => t.id);
}

export function centroid(points: Array<[number, number]>): { x: number; y: number } {
  const n = points.length;
  return {
    x: points.reduce((s, p) => s + p[0], 0) / n,
    y: points.reduce((s, p) => s + p[1], 0) / n,
  };
}

/** Ray-casting point-in-polygon (for label/badge placement). */
export function pointInPolygon(pt: [number, number], poly: Array<[number, number]>): boolean {
  const [x, y] = pt;
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

/** BFS step-distance over all territories (aircraft ignore ground ownership). */
export function airDistance(from: string, to: string): number {
  if (from === to) return 0;
  const dist: Record<string, number> = { [from]: 0 };
  const queue = [from];
  while (queue.length > 0) {
    const cur = queue.shift()!;
    for (const n of neighborsOf(cur)) {
      if (dist[n] === undefined) {
        dist[n] = dist[cur] + 1;
        if (n === to) return dist[n];
        queue.push(n);
      }
    }
  }
  return Infinity;
}

/** Sea zones reachable within `maxSteps` sea moves, traveling only through
 *  zones where `passable` holds. Used for the 2-zone naval movement rule
 *  (1942 2e p.27: "All sea units can move up to two sea zones"). */
export function seaReachable(
  from: string,
  maxSteps: number,
  passable: (id: string) => boolean,
): Set<string> {
  const seen = new Set<string>([from]);
  let frontier = [from];
  for (let step = 0; step < maxSteps; step++) {
    const next: string[] = [];
    for (const cur of frontier) {
      for (const n of neighborsOf(cur)) {
        if (!isSea(n) || seen.has(n) || !passable(n)) continue;
        seen.add(n);
        next.push(n);
      }
    }
    frontier = next;
  }
  seen.delete(from);
  return seen;
}

/**
 * Land paths of up to `maxSteps` from `from`, where each intermediate stop is
 * friendly-owned or blitzable (enemy-owned with zero units). Used for tanks.
 */
export function landPaths(
  from: string,
  maxSteps: number,
  isFriendly: (id: string) => boolean,
  isEmptyEnemy: (id: string) => boolean,
): string[][] {
  const paths: string[][] = [];
  const walk = (cur: string, stepsLeft: number, path: string[]) => {
    if (stepsLeft === 0) return;
    for (const n of neighborsOf(cur)) {
      if (path.includes(n)) continue;
      if (!isFriendly(n) && !isEmptyEnemy(n)) continue;
      const next = [...path, n];
      paths.push(next);
      walk(n, stepsLeft - 1, next);
    }
  };
  walk(from, maxSteps, [from]);
  return paths;
}
